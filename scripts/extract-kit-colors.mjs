// One-time extraction: derive a representative hex color for each kit PNG in
// public/kits, so away/third kit colors can be looked up instead of always
// falling back to a team's static home jerseyBg. Run with: node scripts/extract-kit-colors.mjs
import sharp from 'sharp';
import fs from 'fs';
import path from 'path';

const KITS_DIR = path.resolve('public/kits');
const OUT_FILE = path.resolve('kitColors.ts');

// PNG filename prefix -> internal team ID (inverse of FILE_ID_OVERRIDE in KitImage.tsx)
const FILE_TO_TEAM_ID = {
  HTI: 'HAI',
  PRY: 'PAR',
  CHE: 'SUI',
  SAU: 'KSA',
};

function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h = 0, s = 0;
  const l = (max + min) / 2;
  const d = max - min;
  if (d !== 0) {
    s = d / (1 - Math.abs(2 * l - 1));
    switch (max) {
      case r: h = ((g - b) / d) % 6; break;
      case g: h = (b - r) / d + 2; break;
      case b: h = (r - g) / d + 4; break;
    }
    h *= 60;
    if (h < 0) h += 360;
  }
  return [h, s, l];
}

function toHex(r, g, b) {
  return '#' + [r, g, b].map(v => Math.round(v).toString(16).padStart(2, '0')).join('').toUpperCase();
}

async function extractColor(filePath) {
  const { data, info } = await sharp(filePath).raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info;

  // hue-bucket (20deg) -> { count, rSum, gSum, bSum }
  const colorBuckets = new Map();
  const neutral = {
    white: { count: 0, rSum: 0, gSum: 0, bSum: 0 },
    black: { count: 0, rSum: 0, gSum: 0, bSum: 0 },
    gray: { count: 0, rSum: 0, gSum: 0, bSum: 0 },
  };

  let foreground = 0;
  for (let i = 0; i < width * height; i++) {
    const idx = i * channels;
    const r = data[idx], g = data[idx + 1], b = data[idx + 2];
    const a = channels === 4 ? data[idx + 3] : 255;
    if (a < 200) continue;
    foreground++;

    const [, s, l] = rgbToHsl(r, g, b);
    let bucket;
    if (l > 0.90) bucket = neutral.white;
    else if (l < 0.10) bucket = neutral.black;
    else if (s < 0.20) bucket = neutral.gray;
    else {
      const [h] = rgbToHsl(r, g, b);
      const key = Math.round(h / 20) * 20 % 360;
      if (!colorBuckets.has(key)) colorBuckets.set(key, { count: 0, rSum: 0, gSum: 0, bSum: 0 });
      bucket = colorBuckets.get(key);
    }
    bucket.count++;
    bucket.rSum += r;
    bucket.gSum += g;
    bucket.bSum += b;
  }

  if (foreground === 0) return null;

  const colorTotal = [...colorBuckets.values()].reduce((sum, c) => sum + c.count, 0);
  const candidates = [
    ...[...colorBuckets.entries()].map(([key, c]) => ({ label: `hue${key}`, ...c })),
    { label: 'white', ...neutral.white },
    { label: 'black', ...neutral.black },
    { label: 'gray', ...neutral.gray },
  ].filter(c => c.count > 0).sort((a, b) => b.count - a.count);

  let winner;
  if (colorTotal / foreground >= 0.12) {
    winner = [...colorBuckets.values()].sort((a, b) => b.count - a.count)[0];
  } else {
    winner = [neutral.white, neutral.black, neutral.gray].sort((a, b) => b.count - a.count)[0];
  }

  const hex = toHex(winner.rSum / winner.count, winner.gSum / winner.count, winner.bSum / winner.count);
  const top3 = candidates.slice(0, 3).map(c => `${c.label} ${(c.count / foreground * 100).toFixed(0)}%`).join(', ');
  return { hex, top3 };
}

const files = fs.readdirSync(KITS_DIR).filter(f => f.endsWith('.png'));
const results = {}; // teamId -> { home, away, third }

for (const file of files) {
  const m = file.match(/^([A-Z]{3})-(home|away|third)\.png$/);
  if (!m) { console.warn('skip (unrecognized name):', file); continue; }
  const [, fileId, type] = m;
  const teamId = FILE_TO_TEAM_ID[fileId] ?? fileId;

  const result = await extractColor(path.join(KITS_DIR, file));
  if (!result) { console.warn('skip (no foreground pixels):', file); continue; }

  results[teamId] = results[teamId] || {};
  results[teamId][type] = result.hex;
  console.log(`${teamId}-${type}: ${result.hex}  (${result.top3})`);
}

const sortedTeamIds = Object.keys(results).sort();
const lines = [];
lines.push('// AUTO-GENERATED by scripts/extract-kit-colors.mjs — do not hand-edit without re-running the script.');
lines.push('// Dominant hex color sampled per kit PNG in public/kits, keyed by internal team ID.');
lines.push('export const KIT_COLORS: Record<string, { home?: string; away?: string; third?: string }> = {');
for (const teamId of sortedTeamIds) {
  const { home, away, third } = results[teamId];
  const parts = [];
  if (home) parts.push(`home: '${home}'`);
  if (away) parts.push(`away: '${away}'`);
  if (third) parts.push(`third: '${third}'`);
  lines.push(`  ${teamId}: { ${parts.join(', ')} },`);
}
lines.push('};');

fs.writeFileSync(OUT_FILE, lines.join('\n') + '\n');
console.log(`\nWrote ${OUT_FILE} (${sortedTeamIds.length} teams)`);
